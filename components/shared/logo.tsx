const pixelPaths = PALETTE.map(() => "");

for (let y = 0; y < 64; y++) {
  for (let x = 0; x < 64; x++) {
    if (MONOGRAM[y][x] !== "1") continue;

    const threshold = (DITHER[(y % 4) * 4 + x % 4] + 0.5) / 16;
    const light = 1 - (x / 64 * 0.55 + y / 64 * 0.45);
    const shade = Math.min(3, Math.max(0, Math.floor(-0.1 + light * 2.5 + threshold * 1.7)));
    pixelPaths[shade] += `M${x} ${y}h1v1h-1z`;
  }
}

